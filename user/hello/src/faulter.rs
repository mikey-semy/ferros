//! Пользовательская программа-«фолтер» (M5c3b): намеренно вызывает сбой в кольце 3, чтобы
//! проверить, что ядро **завершает процесс, а не падает само**.
//!
//! `_start` читает заведомо неотображённый адрес → page fault из кольца 3. Ядро должно
//! убить этот процесс (с кодом-сигналом) и продолжить работать.

#![no_std]
#![no_main]

use core::panic::PanicInfo;

/// Точка входа: трогаем неотображённый адрес → #PF из кольца 3. Сюда ядро уже не вернётся
/// (процесс будет завершён обработчиком сбоя).
#[no_mangle]
pub extern "C" fn _start() -> ! {
    // SAFETY: обращение НАМЕРЕННО невалидно — это и проверяем. Адрес 0xDEAD_0000 не
    // отображён в адресном пространстве процесса, поэтому чтение даёт page fault.
    unsafe {
        core::ptr::read_volatile(0xDEAD_0000 as *const u64);
    }
    // Недостижимо: чтение выше уже вызвало сбой и ядро завершило процесс.
    loop {
        core::hint::spin_loop();
    }
}

#[panic_handler]
fn panic(_info: &PanicInfo) -> ! {
    loop {
        core::hint::spin_loop();
    }
}
