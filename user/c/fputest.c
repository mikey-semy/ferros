/*
 * Проверка сохранения FPU/SSE при переключении контекста (M9i). Свободностоящая C-программа.
 *
 * `fork` даёт два процесса; каждый кладёт в xmm0 СВОЁ значение и в длинном цикле проверяет, что
 * оно не изменилось. Под вытеснением планировщик постоянно переключает их туда-сюда, и каждый,
 * когда исполняется, ставит xmm0 = своё. Если бы переключение НЕ сохраняло/восстанавливало FPU
 * (`fxsave`/`fxrstor`), значение одного процесса протекло бы в другой — и при следующей проверке
 * xmm0 не совпал бы. Оба выходят с 0 только если каждый видел РОВНО своё значение; иначе 1.
 *
 * Тест ждёт оба завершения и проверяет сумму кодов выхода == 0.
 */

typedef unsigned long u64;

static long fork_(void) {
    long ret;
    __asm__ volatile("syscall" : "=a"(ret) : "a"(57L) : "rcx", "r11", "memory"); /* SYS_fork */
    return ret;
}

__attribute__((noreturn)) static void exit_(long code) {
    __asm__ volatile("syscall" : : "a"(60L), "D"(code)); /* SYS_exit */
    __builtin_unreachable();
}

/* Кладёт `magic` в xmm0 и `count` раз перечитывает его обратно, сверяя. 1 — всё совпало (значение
 * пережило все переключения), 0 — где-то xmm0 оказался чужим. Весь цикл — в asm, чтобы компилятор
 * не трогал xmm0 между итерациями; между ними возможно вытеснение (IF=1 в кольце 3). */
static int check_xmm(u64 magic, long count) {
    int ok = 0;
    __asm__ volatile(
        "movq %[mag], %%xmm0\n\t" /* xmm0 = magic */
        "1:\n\t"
        "movq %%xmm0, %%rax\n\t" /* rax = xmm0 (низкие 64 бита) */
        "cmpq %[mag], %%rax\n\t"
        "jne 2f\n\t" /* не совпало → провал (ok остаётся 0) */
        "decq %[cnt]\n\t"
        "jnz 1b\n\t"
        "movl $1, %[ok]\n\t" /* цикл прошёл целиком → успех */
        "2:\n\t"
        : [ok] "+r"(ok), [cnt] "+r"(count)
        : [mag] "r"(magic)
        : "xmm0", "rax", "cc");
    return ok;
}

void _start(void) {
    /* Разные значения в низких 64 битах xmm0 у родителя и ребёнка. */
    const u64 parent_magic = 0x1111111122222222UL;
    const u64 child_magic = 0x3333333344444444UL;

    long pid = fork_();
    u64 magic = (pid == 0) ? child_magic : parent_magic;

    /* Цикл должен быть ДОСТАТОЧНО ДЛИННЫМ, чтобы процесс вытеснялся ПОСРЕДИ него, ПОКА второй
     * процесс тоже крутится (иначе каждый успевает отработать целиком в пределах одного тика, не
     * пересекаясь — и утечка FPU не проявилась бы, тест был бы беззубым). 2e8 итераций под QEMU TCG
     * охватывают много тиков (~55 мс/тик), гарантируя мид-цикловые переключения между процессами. */
    int ok = check_xmm(magic, 200000000);
    exit_(ok ? 0 : 1);
}
