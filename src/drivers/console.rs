//! Консоль / линейная дисциплина (M7a): мост между клавиатурой и `read(0)` из кольца 3.
//!
//! # Зачем отдельный слой
//!
//! До M7a клавиатура ([`super::keyboard`]) лишь **печатала** нажатия — пути «клавиатура →
//! пользовательская программа» не было. Shell'у (M7) нужен `stdin`: программа делает
//! `read(0, …)` и получает то, что человек набрал. Между сырыми символами и `read` стоит
//! **линейная дисциплина** — то же, что в Unix-терминале в «каноническом» режиме:
//!
//! - ввод копится **построчно**: пока не нажат Enter, символы лежат в редактируемой строке
//!   ([`Console::line`]) и читателю не видны;
//! - **Enter** (`\n`/`\r`) завершает строку — её байты (с `\n` на конце) уезжают в очередь
//!   готового ([`Console::ready`]), и заблокированные на `read(0)` процессы будятся;
//! - **Backspace** стирает последний символ незавершённой строки (и на экране тоже);
//! - всё набранное **отражается на экран** (echo), как привыкли в терминале.
//!
//! Так `read(0)` отдаёт ввод цельными строками, а редактирование (стереть опечатку до
//! Enter) делает ядро — программе приходит уже «причёсанная» строка.
//!
//! # Кто кого зовёт
//!
//! ```text
//!   keyboard-задача (экзекьютор)        read(0) (кольцо 3, на ядровом стеке процесса)
//!        feed_char(c) ──► line/ready ◄── take_ready(n)
//!                           │                  │ пусто?
//!                  Enter ──►├─ wake_stdin_readers()   └─► block_current_on_stdin()
//! ```
//!
//! # Замок и прерывания
//!
//! Состояние делят keyboard-задача (на «нулевом» потоке) и syscall'ы пользовательских
//! процессов; их может разделить вытеснение по таймеру. Поэтому [`CONSOLE`] берётся **только
//! с выключенными прерываниями** ([`without_interrupts`]): иначе поток, вытесненный с
//! захваченным спин-замком, заблокировал бы другой навсегда (тот же приём, что у планировщика
//! и VGA). Критические секции коротки: под замком только правим буферы, а echo и побудку
//! делаем уже после снятия замка.

use super::vga;
use alloc::collections::VecDeque;
use alloc::vec::Vec;
use spin::Mutex;
use x86_64::instructions::interrupts;

/// Состояние консоли: незавершённая (редактируемая) строка и очередь готовых к чтению байт.
struct Console {
    /// Текущая строка, которую пользователь набирает: символы между двумя Enter. Backspace
    /// стирает с её конца; читателю (`read`) она не видна, пока не завершена Enter.
    line: Vec<u8>,
    /// Байты завершённых строк (FIFO), готовые отдаться `read(0)`. Завершение строки
    /// перекладывает `line` (плюс `\n`) сюда.
    ready: VecDeque<u8>,
}

/// Глобальная консоль. `Option`, чтобы конструироваться `const` (буферы — кучевые, заполняются
/// в [`init`] после поднятия кучи), как и планировщик. Доступ — только под [`without_interrupts`].
static CONSOLE: Mutex<Option<Console>> = Mutex::new(None);

/// Инициализирует консоль (пустые буферы). Вызывать один раз при загрузке — после кучи (буферы
/// аллоцируют) и до первого ввода. Аналог [`super::keyboard::init`].
pub fn init() {
    interrupts::without_interrupts(|| {
        *CONSOLE.lock() = Some(Console {
            line: Vec::new(),
            ready: VecDeque::new(),
        });
    });
}

/// Что отразить на экране после обработки символа (вычисляем под замком, печатаем — без него).
/// `Newline` заодно служит признаком «строка завершена» (по нему будим читателей) — одно
/// состояние вместо отдельного флага. `Copy`, чтобы после `match` ещё раз спросить через `matches!`.
#[derive(Clone, Copy)]
enum Echo {
    /// Напечатать обычный символ.
    Char(u8),
    /// Перевод строки (Enter).
    Newline,
    /// Стереть символ (Backspace).
    Backspace,
    /// Ничего (символ проигнорирован).
    Nothing,
}

/// Принимает один декодированный символ от клавиатуры и прогоняет через линейную дисциплину
/// (M7a). Печатаемые ASCII копятся в текущей строке; Enter завершает строку (отдаёт её
/// читателям и будит заблокированных на `read(0)`); Backspace стирает последний символ.
/// Прочие управляющие и не-ASCII игнорируются (наш буфер и VGA-шрифт — однобайтовые).
///
/// Зовётся из keyboard-задачи (экзекьютор). Echo и побудку делаем уже после снятия замка
/// консоли — не держим его на время вывода на VGA / захода в планировщик.
pub fn feed_char(c: char) {
    if !c.is_ascii() {
        return;
    }
    let byte = c as u8;

    let echo = interrupts::without_interrupts(|| {
        let mut guard = CONSOLE.lock();
        let con = match guard.as_mut() {
            Some(con) => con,
            None => return Echo::Nothing, // ввод до init — игнорируем
        };
        match byte {
            b'\n' | b'\r' => {
                // Завершаем строку: кладём `\n`, перекладываем всю строку в очередь готового.
                con.line.push(b'\n');
                con.ready.extend(con.line.drain(..));
                Echo::Newline
            }
            0x08 | 0x7f => {
                // Backspace/Delete: стираем последний символ незавершённой строки, если есть.
                if con.line.pop().is_some() {
                    Echo::Backspace
                } else {
                    Echo::Nothing
                }
            }
            0x20..=0x7e => {
                con.line.push(byte);
                Echo::Char(byte)
            }
            // Прочие управляющие символы (Tab, Esc, …) пока не поддержаны.
            _ => Echo::Nothing,
        }
    });

    // Echo на экран (замок консоли уже снят; VGA берёт свой замок).
    match echo {
        Echo::Char(b) => vga::write_bytes(&[b]),
        Echo::Newline => vga::write_bytes(b"\n"),
        Echo::Backspace => vga::backspace(),
        Echo::Nothing => {}
    }

    // Строка завершена (Enter) — будим всех, кто заблокирован в `read(0)`, пусть заберут ввод.
    if matches!(echo, Echo::Newline) {
        crate::sched::thread::wake_stdin_readers();
    }
}

/// Забирает до `max` готовых байт из очереди ввода (для `read(0)`). Возвращает столько, сколько
/// есть (не больше `max`); пустой `Vec`, если готового ввода нет (вызывающий тогда блокируется).
/// Готовые байты — это завершённые Enter'ом строки.
pub fn take_ready(max: usize) -> Vec<u8> {
    interrupts::without_interrupts(|| {
        let mut guard = CONSOLE.lock();
        match guard.as_mut() {
            Some(con) => {
                let n = max.min(con.ready.len());
                con.ready.drain(..n).collect()
            }
            None => Vec::new(),
        }
    })
}

/// Возвращает непрочитанные байты в НАЧАЛО очереди готового, сохраняя их порядок. Нужно, когда
/// `read(0)` уже забрал строку через [`take_ready`], но не смог отдать её пользователю (сбой
/// `copy_to_user` → `-EFAULT`): по семантике Linux ошибочный буфер НЕ съедает ввод — следующий
/// `read` должен получить ту же строку, а не потерять её.
pub fn unread(bytes: Vec<u8>) {
    if bytes.is_empty() {
        return;
    }
    interrupts::without_interrupts(|| {
        if let Some(con) = CONSOLE.lock().as_mut() {
            // С конца к началу: каждый push_front встаёт перед предыдущим, восстанавливая порядок.
            for &b in bytes.iter().rev() {
                con.ready.push_front(b);
            }
        }
    });
}
