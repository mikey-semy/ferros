//! `drivers` — драйверы устройств: код, который общается с конкретным «железом».
//!
//! - [`vga`] — текстовый VGA-вывод 80×25 + макросы `print!`/`println!` (M1a).
//! - [`serial`] — UART 16550 на COM1 + макросы `serial_print!`/`serial_println!` (M1b).
//! - [`keyboard`] — async-клавиатура (M4c): обработчик прерывания (в `arch`) только
//!   складывает скан-код в очередь, а декодирование делает async-задача.
//! - [`console`] — линейная дисциплина (M7a): копит ввод построчно и отдаёт его `read(0)`.
//! - [`pci`] — обход шины PCI и модель устройства (M6a): механика портов конфигурации
//!   живёт в `arch::pci` (шов), здесь — переносимое перечисление и разбор BAR'ов.
//! - [`virtio_blk`] — диск virtio-blk (M6b): чтение секторов через virtqueue (DMA).
//!
//! Чтение порта `0x60` и EOI остаются в `arch::x86_64::interrupts` (это x86-специфика);
//! сюда вынесены буфер скан-кодов, поток событий и декодер.

pub mod console;
pub mod keyboard;
pub mod pci;
pub mod serial;
pub mod vga;
pub mod virtio_blk;
