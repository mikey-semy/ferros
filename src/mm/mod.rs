//! `mm` — управление памятью (memory management). Наполняется на **M3**.
//!
//! Планируемые подмодули (по шагам M3):
//! - `paging` (M3a) — доступ к таблицам страниц и трансляция адресов;
//! - `frame` (M3b) — аллокатор физических фреймов из карты памяти bootloader;
//! - `heap` (M3c) — куча ядра (`linked_list_allocator`) → `Box`/`Vec`/`String`.
//!
//! Арх-зависимый механизм (таблицы страниц x86_64) берём из [`crate::arch`];
//! переносимую политику (аллокаторы) держим здесь.
