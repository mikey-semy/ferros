//! `fs` — файловые системы и тонкий слой VFS.
//!
//! - [`fat`] — чтение FAT32 поверх блочного устройства (M6c): разбор BPB, обход цепочек
//!   кластеров, чтение файла из корневого каталога. Только чтение, имена 8.3.
//! - [`open`] — минимальный «VFS»-фасад (M6d2): по пути отдаёт содержимое файла. Сейчас
//!   за ним одна-единственная файловая система (FAT32 на диске virtio-blk).
//!
//! Драйвер диска (virtio-blk) живёт в [`crate::drivers::virtio_blk`]; здесь — разбор
//! содержимого. Полноценный VFS (несколько ФС, точки монтирования, инодовый слой) — позже.

pub mod fat;

use alloc::vec::Vec;

/// Открывает файл по пути и возвращает всё его содержимое.
///
/// «VFS» пока вырожденный: единственная ФС — FAT32 на диске; путь — имя файла в корне (8.3),
/// ведущий `/` игнорируется. Монтируем том на каждый вызов (дёшево: один сектор BPB) и
/// читаем файл. Кэш/настоящие точки монтирования — позже (HARDENING).
pub fn open(path: &str) -> Result<Vec<u8>, fat::FatError> {
    let name = path.trim_start_matches('/');
    let volume = fat::Fat32::mount()?;
    volume.read_file(name)
}
