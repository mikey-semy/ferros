//! `sched` — кооперативная многозадачность на `async`/`await` (M4).
//!
//! # Идея кооперативных задач
//!
//! «Задача» — исполняемая единица работы, обёрнутая в Rust-future. В отличие от
//! потоков ОС, кооперативные задачи переключаются только **добровольно** — в точках
//! `.await`, где future возвращает `Poll::Pending`. Никаких прерываний по таймеру и
//! сохранения регистров: всё происходит в обычном коде, поэтому переключение почти
//! бесплатное. «Экзекьютор» (планировщик) по очереди опрашивает (`poll`) задачи.
//!
//! - [`Task`] — обёртка над `Pin<Box<dyn Future>>` (вот где пригодилась куча из M3).
//! - [`simple_executor::SimpleExecutor`] (M4a) — простейший экзекьютор: крутит очередь
//!   задач, опрашивая их с «пустым» waker'ом. Позже (M4b) — эффективный экзекьютор с
//!   настоящими waker'ами, который спит на `hlt`, пока задачам нечего делать.
//!
//! Вытесняющая многозадачность (переключение контекста по таймеру) — арх-зависимая и
//! придёт отдельной фазой (см. `docs/ROADMAP.md`, M4 фаза 2).

pub mod simple_executor;

use alloc::boxed::Box;
use core::future::Future;
use core::pin::Pin;
use core::task::{Context, Poll};

/// Одна кооперативная задача — future без результата, размещённый на куче и
/// «закреплённый» в памяти ([`Pin`]): future после старта нельзя двигать, потому что
/// он может хранить ссылки сам на себя.
pub struct Task {
    future: Pin<Box<dyn Future<Output = ()>>>,
}

impl Task {
    /// Оборачивает любой `'static` future в задачу.
    pub fn new(future: impl Future<Output = ()> + 'static) -> Task {
        Task {
            future: Box::pin(future),
        }
    }

    /// Опрашивает задачу один раз. `Ready` — задача завершилась; `Pending` — уступила
    /// управление и ждёт пробуждения через `Context`'s waker.
    fn poll(&mut self, context: &mut Context) -> Poll<()> {
        self.future.as_mut().poll(context)
    }
}
