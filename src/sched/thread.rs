//! Потоки ядра с переключением контекста: кооперативное (M4d) и **вытесняющее по
//! таймеру** (M4e).
//!
//! # Чем поток отличается от async-задачи
//!
//! Async-[`Task`](super::Task) — это future: он добровольно уступает в `.await`, и у
//! него нет собственного стека (состояние компилятор зашивает в стейт-машину).
//! **Поток** же — это отдельный стек + сохранённый набор регистров; он может уступить
//! в любой точке кода, потому что мы умеем сохранить/восстановить его регистры
//! ([`crate::arch::context`]).
//!
//! # Две причины переключиться
//!
//! 1. **Кооперативно** — поток сам зовёт [`yield_now`] (M4d). Удобно для «я подождy».
//! 2. **Вытесняюще** — поток НИЧЕГО не зовёт, его прерывает таймер (M4e). Обработчик
//!    таймера дёргает [`on_timer_tick`], и тот переключает на следующий поток помимо
//!    воли текущего. Это и есть настоящая многозадачность: одно тугое ядро делят
//!    несколько потоков, и зависший в `loop {}` поток не захватывает CPU навсегда.
//!
//! Оба пути сходятся в одном месте — [`switch_to_next`], — поэтому переключение
//! устроено одинаково независимо от того, кто его инициировал. Планировщик простой
//! round-robin. «Нулевой» поток — текущий контекст ядра (его стек завёл загрузчик);
//! остальные получают свежий стек в куче.
//!
//! # Почему вытеснение «бесплатно» переиспользует [`switch_to_next`]
//!
//! Обработчик таймера объявлен `extern "x86-interrupt"` и **содержит вызовы** (атомик,
//! EOI, сам `switch_context`). По System V любой `call` затирает caller-saved регистры,
//! поэтому компилятор обязан сохранить в прологе обработчика ВСЕ caller-saved регистры
//! прерванного потока (иначе он не смог бы вернуть их нетронутыми по `iretq`).
//! Callee-saved сохраняет уже сам `switch_context`. Вместе это — полный набор регистров
//! потока, так что переключение прямо из обработчика корректно. Подробный разбор — в
//! [`crate::arch::context`].

use alloc::boxed::Box;
use alloc::vec;
use alloc::vec::Vec;
use core::sync::atomic::{AtomicBool, Ordering};
use spin::Mutex;
use x86_64::instructions::interrupts;

/// Размер стека одного потока ядра (16 КиБ).
const STACK_SIZE: usize = 4096 * 4;

/// Включено ли вытеснение по таймеру. Пока `false`, обработчик таймера только считает
/// тики и не трогает потоки (поведение M2–M4d). Взводится [`start_preemption`].
static PREEMPTION_ENABLED: AtomicBool = AtomicBool::new(false);

/// Контекст потока: сохранённый указатель стека плюс владение его памятью.
struct Thread {
    /// Сохранённый `rsp` потока. Пока поток исполняется, значение неактуально;
    /// обновляется в момент переключения прочь.
    rsp: u64,
    /// Память стека. `None` у «нулевого» потока — он работает на стеке ядра от
    /// загрузчика. Поле держит память живой; напрямую не читается.
    _stack: Option<Box<[u8]>>,
}

/// Простой round-robin планировщик потоков ядра.
struct Scheduler {
    threads: Vec<Thread>,
    current: usize,
}

static SCHEDULER: Mutex<Option<Scheduler>> = Mutex::new(None);

/// Инициализирует планировщик «нулевым» потоком — текущим контекстом ядра. Его `rsp`
/// заполнится при первом переключении прочь. Вызывать один раз, после инициализации
/// кучи (потоки выделяют стеки в куче).
pub fn init() {
    // Без прерываний: замок `SCHEDULER` берёт и обработчик таймера (см. правило
    // дедлока в CONVENTIONS.md §4), поэтому держим его только с IF=0.
    interrupts::without_interrupts(|| {
        let mut guard = SCHEDULER.lock();
        *guard = Some(Scheduler {
            threads: vec![Thread {
                rsp: 0,
                _stack: None,
            }],
            current: 0,
        });
    });
}

/// Создаёт поток с точкой входа `entry` (она не должна возвращаться — её тип `-> !`).
///
/// # Panics
/// Если планировщик не инициализирован ([`init`]).
pub fn spawn(entry: extern "C" fn() -> !) {
    let mut stack = vec![0u8; STACK_SIZE].into_boxed_slice();

    // Вершина стека (старший адрес), выровненная вниз по 16 байт.
    let top = stack.as_mut_ptr() as usize + stack.len();
    let top = (top & !0xF) as *mut u8;

    // SAFETY: `top` — вершина только что выделенного выровненного стека достаточного
    // размера; `entry` имеет тип `-> !` и не вернётся.
    let rsp = unsafe { crate::arch::context::init_thread_stack(top, entry) };

    // Без прерываний: пока мы меняем `threads`, таймер не должен войти в планировщик
    // (тот же замок). Заодно если Vec переаллоцируется, никакой обработчик не держит
    // в этот момент сырой указатель в старый буфер.
    interrupts::without_interrupts(|| {
        let mut guard = SCHEDULER.lock();
        let sched = guard.as_mut().expect("scheduler not initialized");
        sched.threads.push(Thread {
            rsp,
            _stack: Some(stack),
        });
    });
}

/// Включает вытеснение по таймеру: с этого момента каждый тик может переключить потоки.
/// Вызывать после [`init`] и создания хотя бы одного [`spawn`] потока.
pub fn start_preemption() {
    PREEMPTION_ENABLED.store(true, Ordering::SeqCst);
}

/// Выключает вытеснение по таймеру (потоки остаются, но таймер их больше не переключает).
pub fn stop_preemption() {
    PREEMPTION_ENABLED.store(false, Ordering::SeqCst);
}

/// Точка входа вытеснения: её зовёт обработчик таймера на каждом тике. Если вытеснение
/// включено, переключает на следующий поток round-robin; иначе — ничего не делает.
///
/// # Safety
/// Вызывать **только из контекста прерывания с IF=0** (как делает обработчик таймера).
/// [`switch_to_next`] переключает контекст без сохранения/восстановления IF: если IF=1,
/// таймер может прийти прямо в середину `switch_context` (между сменой `rsp` и снятием
/// регистров) и реентрантно переключиться на полу-восстановленном контексте — UB.
/// Восстановление IF после возврата в поток делает `iretq` обработчика.
pub unsafe fn on_timer_tick() {
    if PREEMPTION_ENABLED.load(Ordering::SeqCst) {
        switch_to_next();
    }
}

/// Уступает CPU следующему потоку (round-robin) — **кооперативно**. Если поток всего
/// один, ничего не делает. Переключение выполняется с выключенными прерываниями
/// (атомарно), а исходное состояние IF восстанавливается после возврата в этот поток.
pub fn yield_now() {
    let was_enabled = interrupts::are_enabled();
    interrupts::disable();

    switch_to_next();

    if was_enabled {
        interrupts::enable();
    }
}

/// Переключает на следующий поток (round-robin). Возвращает `true`, если переключение
/// произошло, `false` — если переключаться не на кого (потоков меньше двух или
/// планировщик не инициализирован).
///
/// Вызывать **с выключенными прерываниями**: и кооперативный ([`yield_now`]), и
/// вытесняющий ([`on_timer_tick`]) пути входят сюда с IF=0. Замок планировщика берём,
/// считаем указатели на контексты и **отпускаем замок до переключения** — держать его
/// через `switch_context` нельзя: мы уйдём в другой поток, `guard.drop()` не выполнится,
/// и замок остался бы захваченным навсегда.
fn switch_to_next() -> bool {
    let switch = {
        let mut guard = SCHEDULER.lock();
        match guard.as_mut() {
            Some(sched) if sched.threads.len() >= 2 => {
                let cur = sched.current;
                let next = (cur + 1) % sched.threads.len();
                sched.current = next;
                let old_rsp: *mut u64 = &mut sched.threads[cur].rsp;
                let new_rsp: u64 = sched.threads[next].rsp;
                Some((old_rsp, new_rsp))
            }
            _ => None,
        }
    };

    match switch {
        Some((old_rsp, new_rsp)) => {
            // SAFETY: указатели — из валидных контекстов потоков. Прерывания выключены,
            // поэтому между отпусканием замка и записью `*old_rsp` (самое начало
            // switch_context, до прыжка) никакой другой код Vec не перелокует — сырой
            // указатель не успеет «протухнуть».
            unsafe { crate::arch::context::switch_context(old_rsp, new_rsp) };
            true
        }
        None => false,
    }
}
