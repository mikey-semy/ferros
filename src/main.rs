//! Ядро ferros — точка входа.
//!
//! M0: минимальное загружаемое ядро. Никакой стандартной библиотеки (`no_std`)
//! и никакой обычной функции `main` (`no_main`) — мы на голом железе, до запуска
//! рантайма. Bootloader передаёт управление по символу `_start`, и наша задача
//! пока скромная: вывести строку прямо в текстовый VGA-буфер и встать в idle.
//!
//! Абстракцию над VGA, макросы `println!` и прочую инфраструктуру добавим в M1.

#![no_std]
#![no_main]

use core::panic::PanicInfo;

/// Строка-приветствие, которую печатаем при загрузке.
static GREETING: &[u8] = b"ferros booting...";

/// Точка входа ядра.
///
/// Bootloader (крейт `bootloader` 0.9) ищет символ `_start` и прыгает сюда.
/// Возврата быть не может — отсюда тип `-> !`. `#[no_mangle]` сохраняет имя
/// символа, `extern "C"` задаёт C-ABI, которое ожидает загрузчик.
#[unsafe(no_mangle)]
pub extern "C" fn _start() -> ! {
    // Текстовый VGA-буфер начинается с физического адреса 0xb8000.
    // Каждый символ занимает 2 байта: [ASCII-код][байт атрибута (цвет)].
    let vga = 0xb8000 as *mut u8;
    let color: u8 = 0x0f; // ярко-белый текст на чёрном фоне

    for (i, &byte) in GREETING.iter().enumerate() {
        // SAFETY: 0xb8000 — это MMIO-область текстового VGA, гарантированно
        // доступная во время загрузки в BIOS-режиме; индекс не выходит за
        // пределы 80x25 экрана (строка короткая).
        unsafe {
            core::ptr::write_volatile(vga.add(i * 2), byte);
            core::ptr::write_volatile(vga.add(i * 2 + 1), color);
        }
    }

    halt_loop();
}

/// Обработчик паники. На голом железе стандартного нет — обязаны определить свой.
/// Пока просто останавливаем процессор; человекочитаемый вывод добавим в M1.
#[panic_handler]
fn panic(_info: &PanicInfo) -> ! {
    halt_loop();
}

/// Бесконечный idle: останавливаем CPU инструкцией `hlt` до следующего
/// прерывания. Это эффективнее «горячего» `loop {}` — процессор не греется впустую.
fn halt_loop() -> ! {
    loop {
        // SAFETY: `hlt` — безопасная для нас привилегированная инструкция,
        // переводящая ядро в ожидание прерывания.
        unsafe { core::arch::asm!("hlt") };
    }
}
