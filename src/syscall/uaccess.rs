//! Безопасный доступ к памяти пользователя (M5b) — намеренный «шов» для опасного (D9).
//!
//! # Зачем отдельный модуль
//!
//! Аргументы системных вызовов часто — это **указатели в память пользователя** (буфер
//! для `write`, путь для `open`, …). Ядро не может слепо им доверять: пользователь мог
//! передать адрес в память ядра (чтобы выманить секреты через `write`) или вовсе
//! невалидный адрес. Поэтому ВСЯ работа с сырыми пользовательскими указателями собрана
//! здесь, за проверкой границ, и каждый сырой доступ снабжён `// SAFETY` (D9). Остальной
//! слой [`crate::syscall`] остаётся безопасным Rust.
//!
//! # Что проверяем (и что пока нет)
//!
//! Проверяем, что диапазон `[ptr, ptr+len)` целиком лежит в **пользовательской** половине
//! адресного пространства (нижняя каноническая половина x86-64). Это закрывает «передал
//! адрес ядра». Чего пока НЕ делаем: устойчивости к *невалидному, но пользовательскому*
//! указателю — если он не отображён, чтение упадёт в page fault (сейчас это паника). По-
//! настоящему отказоустойчивый доступ (таблица fixup'ов / extable) — в HARDENING.md.

use super::abi;

/// Верхняя граница пользовательской половины адресного пространства на x86-64 с
/// 4-уровневыми таблицами: канонические пользовательские адреса — это `[0, 2^47)`.
/// Всё, что выше, — «дыра» неканонических адресов и половина ядра.
///
/// (Значение арх-специфично; при портировании на другую ISA вынесем за `arch`-шов.)
const USER_SPACE_END: u64 = 0x0000_8000_0000_0000;

/// Проверяет, что диапазон `[ptr, ptr+len)` целиком в пользовательской половине и не
/// переполняется. Возвращает `Err(EFAULT)`, если нет.
fn validate(ptr: u64, len: u64) -> Result<(), i64> {
    match ptr.checked_add(len) {
        Some(end) if end <= USER_SPACE_END => Ok(()),
        _ => Err(abi::EFAULT),
    }
}

/// Выполняет `f` с временным `&[u8]`-видом на пользовательский буфер `[ptr, len)`.
/// Указатель сначала валидируется (иначе `Err(EFAULT)`). Весь сырой доступ — здесь.
///
/// Вид действителен только на время `f`; наружу его не отдаём (он алиасит чужую память).
pub fn with_user_bytes<R>(ptr: u64, len: u64, f: impl FnOnce(&[u8]) -> R) -> Result<R, i64> {
    validate(ptr, len)?;
    // SAFETY: диапазон проверен — он в пользовательской половине. Мы на одном ядре и
    // внутри обработчика syscall с IF=0, поэтому отображение не изменится под нами, а
    // вид не живёт дольше `f`. (Невалидный-но-пользовательский указатель здесь упадёт в
    // page fault — отказоустойчивость отложена, см. HARDENING.md.)
    let bytes = unsafe { core::slice::from_raw_parts(ptr as *const u8, len as usize) };
    Ok(f(bytes))
}
