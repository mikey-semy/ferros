//! Безопасный доступ к памяти пользователя (M5b) — намеренный «шов» для опасного (D9).
//!
//! # Зачем отдельный модуль
//!
//! Аргументы системных вызовов часто — это **указатели в память пользователя** (буфер
//! для `write`, путь для `open`, …). Ядро не может слепо им доверять: пользователь мог
//! передать адрес в память ядра (чтобы выманить секреты через `write`) или вовсе
//! невалидный адрес. Поэтому ВСЯ работа с сырыми пользовательскими указателями собрана
//! здесь, за проверкой границ, и каждый сырой доступ снабжён `// SAFETY` (D9). Остальной
//! слой [`crate::syscall`] остаётся безопасным Rust.
//!
//! # Что проверяем (M6d1)
//!
//! Две ступени, обе до доступа к памяти:
//! 1. диапазон `[ptr, ptr+len)` целиком в **пользовательской** половине адресного
//!    пространства (закрывает «передал адрес ядра») — дёшево, без обхода таблиц;
//! 2. каждая страница диапазона реально **отображена как пользовательская** в активном
//!    адресном пространстве ([`crate::mm::paging::user_range_accessible`]). Это и делает
//!    доступ **отказоустойчивым**: на невалидном-но-пользовательском указателе мы возвращаем
//!    `-EFAULT`, а не падаем в page fault (раньше это роняло ядро).
//!
//! Корректно на одном ядре: syscall идёт с `IF=0`, поэтому между проверкой и доступом
//! отображение не меняется (на SMP нужен fault-fixup/extable — см. HARDENING.md).

use super::abi;
use alloc::vec::Vec;
// Граница пользовательской/ядерной половин — арх-специфична, берём её из `arch`-шва (D7),
// чтобы этот переносимый модуль не зашивал разметку конкретной архитектуры.
use crate::arch::USER_SPACE_END;

/// Максимальная длина пути, читаемого из памяти пользователя (M6d2).
const PATH_MAX: usize = 256;

/// Проверяет, что диапазон `[ptr, ptr+len)` целиком в пользовательской половине и не
/// переполняется. Возвращает `Err(EFAULT)`, если нет.
fn validate(ptr: u64, len: u64) -> Result<(), i64> {
    match ptr.checked_add(len) {
        Some(end) if end <= USER_SPACE_END => Ok(()),
        _ => Err(abi::EFAULT),
    }
}

/// Выполняет `f` с временным `&[u8]`-видом на пользовательский буфер `[ptr, len)`.
/// Возвращает `Err(EFAULT)`, если диапазон вне пользовательской половины ИЛИ не отображён
/// как пользовательский (тогда `f` не вызывается и память не трогается). Весь сырой
/// доступ — здесь.
///
/// Вид действителен только на время `f`; наружу его не отдаём (он алиасит чужую память).
pub fn with_user_bytes<R>(ptr: u64, len: u64, f: impl FnOnce(&[u8]) -> R) -> Result<R, i64> {
    validate(ptr, len)?;
    // Пустой буфер: читать нечего. Заодно не строим срез из, возможно, нулевого указателя —
    // `from_raw_parts` требует ненулевой указатель даже при len == 0.
    if len == 0 {
        return Ok(f(&[]));
    }
    // Предпроверка отображения: иначе чтение невалидного указателя упало бы в page fault и
    // уронило ядро. Проверяем ДО создания среза.
    if !crate::mm::paging::user_range_accessible(ptr, len, false) {
        return Err(abi::EFAULT);
    }
    // SAFETY: диапазон проверен — он в пользовательской половине И каждая его страница
    // отображена present+user. На одном ядре с IF=0 отображение не изменится до конца
    // обработчика, поэтому доступ не упадёт; вид не живёт дольше `f`.
    let bytes = unsafe { core::slice::from_raw_parts(ptr as *const u8, len as usize) };
    Ok(f(bytes))
}

/// Копирует `src` В буфер пользователя по адресу `dst` (для `read`: отдаём прочитанные
/// байты). Проверяет, что весь диапазон в пользовательской половине и отображён как
/// **записываемый пользовательский** — иначе `Err(EFAULT)`, ничего не записав.
pub fn copy_to_user(dst: u64, src: &[u8]) -> Result<(), i64> {
    let len = src.len() as u64;
    validate(dst, len)?;
    if src.is_empty() {
        return Ok(());
    }
    if !crate::mm::paging::user_range_accessible(dst, len, true) {
        return Err(abi::EFAULT);
    }
    // SAFETY: диапазон проверен (пользовательская половина, present+user+writable); IF=0,
    // поэтому отображение стабильно; пишем ровно `src.len()` байт, буферы не пересекаются
    // (src — память ядра, dst — пользователя).
    unsafe {
        core::ptr::copy_nonoverlapping(src.as_ptr(), dst as *mut u8, src.len());
    }
    Ok(())
}

/// Читает из памяти пользователя нуль-терминированную строку (путь для `open`), начиная с
/// `ptr`, не длиннее [`PATH_MAX`]. Идёт постранично (каждая страница предпроверяется
/// `with_user_bytes`), останавливается на нулевом байте. `Err(EFAULT)` на недоступной
/// странице, `Err(EINVAL)` если нуль не встретился в пределах лимита.
pub fn read_user_cstr(ptr: u64) -> Result<Vec<u8>, i64> {
    let mut out = Vec::new();
    let mut addr = ptr;
    loop {
        // Читаем до конца текущей страницы (но не больше остатка лимита) — так не пересекаем
        // границу страницы в одном `with_user_bytes` (следующая может быть не отображена).
        let page_end = (addr | 0xFFF) + 1;
        let chunk_len = (page_end - addr).min((PATH_MAX - out.len()) as u64);
        if chunk_len == 0 {
            return Err(abi::EINVAL); // достигли PATH_MAX без нулевого байта
        }
        let hit_nul = with_user_bytes(addr, chunk_len, |bytes| {
            for &b in bytes {
                if b == 0 {
                    return true;
                }
                out.push(b);
            }
            false
        })?;
        if hit_nul {
            return Ok(out);
        }
        addr = page_end;
    }
}
