//! Арх-зависимый слой (HAL-шов).
//!
//! Единственное место в ядре, которое знает про конкретный CPU/платформу. Всё, что
//! выше по стеку (`mm`, `sched`, `fs`, …), обращается к железу только через
//! нейтральный интерфейс этого модуля ([`init`] и публичные элементы подмодулей).
//! Благодаря этому порт на другую архитектуру = добавить подмодуль рядом, не трогая
//! остальное ядро. Сейчас поддержан x86_64; ARM64/RISC-V — отдельный трек
//! (см. `docs/ROADMAP.md`).

#[cfg(target_arch = "x86_64")]
pub mod x86_64;

// Арх-нейтральный псевдоним для переключения контекста (M4d): переносимый `sched`
// зовёт `arch::context::*`, не зная конкретной архитектуры.
#[cfg(target_arch = "x86_64")]
pub use self::x86_64::context;

// Арх-нейтральная граница память-пользователя/память-ядра (M5b): переносимый `syscall`
// (uaccess) проверяет указатели пользователя, не зная разметки конкретной архитектуры.
#[cfg(target_arch = "x86_64")]
pub use self::x86_64::USER_SPACE_END;

// Арх-нейтральная разметка кучи процесса (M9a): переносимый `brk` ([`crate::syscall::files`])
// знает базу и предел кучи, но не конкретную раскладку VA.
#[cfg(target_arch = "x86_64")]
pub use self::x86_64::{USER_HEAP_BASE, USER_HEAP_MAX};

// Арх-нейтральный доступ к конфигурационному пространству PCI (M6a): переносимый драйвер
// PCI ([`crate::drivers::pci`]) обходит шину через этот шов, не зная механики портов.
#[cfg(target_arch = "x86_64")]
pub use self::x86_64::pci;

// Арх-нейтральный ввод-вывод по портам с динамическим номером (M6b): драйверы устройств
// с I/O-BAR (legacy virtio) читают/пишут регистры через этот шов.
#[cfg(target_arch = "x86_64")]
pub use self::x86_64::io;

/// Инициализация процессора под текущую целевую архитектуру (роутинг по `cfg`).
#[cfg(target_arch = "x86_64")]
pub fn init() {
    self::x86_64::init();
}
