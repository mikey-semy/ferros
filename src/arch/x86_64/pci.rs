//! Доступ к конфигурационному пространству PCI через порты 0xCF8/0xCFC (x86-специфика, M6a).
//!
//! # Что такое PCI и зачем «конфигурационное пространство»
//!
//! PCI — шина, к которой подключены устройства (диски, сетевые карты, контроллеры). У
//! каждого устройства есть 256-байтная «анкета» — *конфигурационное пространство*: кто
//! производитель, что за устройство, какого оно класса и где лежат его регистры (BAR'ы).
//! Чтобы прочитать анкету на x86 «классическим» механизмом #1, есть два 32-битных порта:
//!
//! - `CONFIG_ADDRESS` (0xCF8) — туда пишем «координаты»: шина / слот (устройство) /
//!   функция / смещение регистра.
//! - `CONFIG_DATA` (0xCFC) — оттуда затем читаем (или туда пишем) 32-битное слово.
//!
//! Это и есть арх-шов (CONVENTIONS §1): сама механика портов — x86-специфика (на ARM к
//! PCI обращаются иначе, через MMIO ECAM), поэтому она здесь, в `arch`. Переносимая модель
//! устройств и обход шины — в [`crate::drivers::pci`].

use x86_64::instructions::interrupts::without_interrupts;
use x86_64::instructions::port::Port;

/// Порт «адреса»: сюда пишем координаты регистра конфигурации.
const CONFIG_ADDRESS: u16 = 0xCF8;
/// Порт «данных»: отсюда читаем / сюда пишем слово по выбранному адресу.
const CONFIG_DATA: u16 = 0xCFC;

/// Собирает 32-битное значение для `CONFIG_ADDRESS`. Бит 31 — «включить» обращение; далее
/// упакованы шина, слот, функция и смещение регистра, выровненное на 4 (младшие 2 бита 0).
fn address(bus: u8, slot: u8, func: u8, offset: u8) -> u32 {
    0x8000_0000
        | ((bus as u32) << 16)
        | ((slot as u32) << 11)
        | ((func as u32) << 8)
        | ((offset as u32) & 0xFC)
}

/// Читает 32-битное слово из конфигурационного пространства устройства `bus:slot.func` по
/// смещению `offset` (внутри выравнивается на 4).
pub fn config_read_u32(bus: u8, slot: u8, func: u8, offset: u8) -> u32 {
    let addr = address(bus, slot, func, offset);
    // Пара «записать адрес → прочитать данные» должна быть атомарной: если между ними
    // другое обращение к PCI (скажем, из обработчика прерывания) перепишет 0xCF8, мы
    // прочитаем не тот регистр. На одном ядре `without_interrupts` это гарантирует.
    without_interrupts(|| {
        let mut address_port = Port::<u32>::new(CONFIG_ADDRESS);
        let mut data_port = Port::<u32>::new(CONFIG_DATA);
        // SAFETY: 0xCF8/0xCFC — стандартные порты механизма конфигурации PCI #1. Запись
        // адреса и чтение данных не имеют побочных эффектов на память ядра.
        unsafe {
            address_port.write(addr);
            data_port.read()
        }
    })
}

/// Пишет 32-битное слово в конфигурационное пространство устройства. Понадобится в M6b
/// (включить bus-mastering в регистре команд по смещению 0x04, настроить очередь virtio).
pub fn config_write_u32(bus: u8, slot: u8, func: u8, offset: u8, value: u32) {
    let addr = address(bus, slot, func, offset);
    without_interrupts(|| {
        let mut address_port = Port::<u32>::new(CONFIG_ADDRESS);
        let mut data_port = Port::<u32>::new(CONFIG_DATA);
        // SAFETY: см. `config_read_u32`; пишем 32-битное слово по уже выбранному адресу.
        unsafe {
            address_port.write(addr);
            data_port.write(value);
        }
    })
}
