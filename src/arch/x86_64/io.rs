//! Порты ввода-вывода x86 с **динамическим** номером порта (M6b).
//!
//! Большинство наших драйверов знают свои порты на этапе компиляции (COM1 `0x3F8`,
//! PS/2 `0x60`). Но устройство на шине PCI сообщает базовый порт своих регистров через
//! BAR во время выполнения (у legacy virtio это I/O-BAR0). Драйверу нужен способ читать/
//! писать порт, номер которого известен лишь в рантайме — это и есть данный шов
//! (CONVENTIONS §1: вся работа с портами — в `arch`).
//!
//! Обёртки тонкие: создаём `Port<T>` на нужный порт и делаем одно чтение/запись. Все они
//! `unsafe` — вызывающий отвечает за то, что порт корректен для устройства (обращение к
//! произвольному порту может управлять железом).

use x86_64::instructions::port::Port;

/// Читает байт из порта `port`.
///
/// # Safety
/// `port` должен быть валидным портом устройства; чтение может иметь побочные эффекты.
pub unsafe fn inb(port: u16) -> u8 {
    Port::<u8>::new(port).read()
}

/// Пишет байт `value` в порт `port`.
///
/// # Safety
/// `port` должен быть валидным портом устройства; запись управляет железом.
pub unsafe fn outb(port: u16, value: u8) {
    Port::<u8>::new(port).write(value)
}

/// Читает 16-битное слово из порта `port`.
///
/// # Safety
/// См. [`inb`].
pub unsafe fn inw(port: u16) -> u16 {
    Port::<u16>::new(port).read()
}

/// Пишет 16-битное слово `value` в порт `port`.
///
/// # Safety
/// См. [`outb`].
pub unsafe fn outw(port: u16, value: u16) {
    Port::<u16>::new(port).write(value)
}

/// Читает 32-битное слово из порта `port`.
///
/// # Safety
/// См. [`inb`].
pub unsafe fn inl(port: u16) -> u32 {
    Port::<u32>::new(port).read()
}

/// Пишет 32-битное слово `value` в порт `port`.
///
/// # Safety
/// См. [`outb`].
pub unsafe fn outl(port: u16, value: u32) {
    Port::<u32>::new(port).write(value)
}
