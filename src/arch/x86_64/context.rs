//! Переключение контекста между потоками ядра на x86_64 (M4d).
//!
//! # Что такое «контекст» и как его переключают
//!
//! У каждого потока — свой **стек** и свой набор регистров. «Переключить контекст» =
//! сохранить регистры текущего потока, поставить регистры другого и продолжить с того
//! места, где тот поток в прошлый раз остановился.
//!
//! По System V ABI вызывающая функция может рассчитывать, что **callee-saved**
//! регистры (`rbx`, `rbp`, `r12`–`r15`) переживут вызов. Поэтому при кооперативном
//! переключении (через обычный вызов) достаточно сохранить только их и указатель
//! стека `rsp` — остальное компилятор уже сохранил вокруг вызова сам.
//!
//! [`switch_context`] делает ровно это: кладёт callee-saved на стек текущего потока,
//! записывает его `rsp` в `*old_rsp`, ставит `rsp` нового потока, снимает его
//! callee-saved и `ret`'ом «возвращается» туда, где новый поток остановился.
//!
//! У свежесозданного потока стек подготовлен [`init_thread_stack`] так, что первый
//! `ret` прыгает в его точку входа.

// Реализация на ассемблере: чистый пролог/эпилог без участия компилятора.
// Синтаксис Intel (по умолчанию в Rust). Аргументы по System V: rdi = old_rsp
// (куда сохранить текущий rsp), rsi = new_rsp (какой rsp восстановить).
core::arch::global_asm!(
    ".global ferros_switch_context",
    "ferros_switch_context:",
    "    push rbp",
    "    push rbx",
    "    push r12",
    "    push r13",
    "    push r14",
    "    push r15",
    "    mov [rdi], rsp", // сохранить rsp текущего потока в *old_rsp
    "    mov rsp, rsi",   // переключиться на стек нового потока
    "    pop r15",
    "    pop r14",
    "    pop r13",
    "    pop r12",
    "    pop rbx",
    "    pop rbp",
    "    ret", // «вернуться» в новый поток (его сохранённый адрес возврата)
);

extern "C" {
    fn ferros_switch_context(old_rsp: *mut u64, new_rsp: u64);
}

/// Переключает контекст с текущего потока на другой.
///
/// Сохраняет callee-saved и `rsp` текущего потока (записывая `rsp` в `*old_rsp`),
/// затем восстанавливает контекст потока с `new_rsp`. Возврат из этой функции
/// произойдёт, когда кто-нибудь переключится обратно на текущий поток.
///
/// # Safety
///
/// `old_rsp` должен указывать на валидную ячейку для сохранения `rsp`. `new_rsp`
/// должен быть корректным сохранённым (или подготовленным [`init_thread_stack`])
/// указателем стека. Вызывать с выключенными прерываниями.
pub unsafe fn switch_context(old_rsp: *mut u64, new_rsp: u64) {
    ferros_switch_context(old_rsp, new_rsp);
}

/// Готовит стек нового потока так, чтобы первое переключение на него прыгнуло в
/// `entry`. Возвращает начальный `rsp` потока (для передачи в [`switch_context`]).
///
/// Раскладка кадра (от старших адресов к младшим): `[entry][rbp][rbx][r12..r15]`.
/// При переключении [`switch_context`] снимет шесть нулевых callee-saved, а `ret`
/// заберёт `entry`.
///
/// # Safety
///
/// `stack_top` должен указывать на вершину (старший адрес) выделенной, выровненной по
/// 16 байт области стека, в которой есть место хотя бы под 7 машинных слов. `entry`
/// не должна возвращаться (тип `-> !`): возвращаться ей некуда.
pub unsafe fn init_thread_stack(stack_top: *mut u8, entry: extern "C" fn() -> !) -> u64 {
    let mut sp = stack_top as *mut u64;

    // Адрес возврата: первый `ret` прыгнет сюда — в точку входа потока.
    sp = sp.sub(1);
    sp.write(entry as usize as u64);

    // Шесть callee-saved регистров (rbp, rbx, r12–r15), начально нулевые.
    for _ in 0..6 {
        sp = sp.sub(1);
        sp.write(0);
    }

    sp as u64
}
