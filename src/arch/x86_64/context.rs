//! Переключение контекста между потоками ядра на x86_64 (M4d), переиспользуемое и
//! вытеснением по таймеру (M4e).
//!
//! # Что такое «контекст» и как его переключают
//!
//! У каждого потока — свой **стек** и свой набор регистров. «Переключить контекст» =
//! сохранить регистры текущего потока, поставить регистры другого и продолжить с того
//! места, где тот поток в прошлый раз остановился.
//!
//! По System V ABI вызывающая функция может рассчитывать, что **callee-saved**
//! регистры (`rbx`, `rbp`, `r12`–`r15`) переживут вызов. Поэтому при кооперативном
//! переключении (через обычный вызов) достаточно сохранить только их и указатель
//! стека `rsp` — остальное компилятор уже сохранил вокруг вызова сам.
//!
//! [`switch_context`] делает ровно это: кладёт callee-saved на стек текущего потока,
//! записывает его `rsp` в `*old_rsp`, ставит `rsp` нового потока, снимает его
//! callee-saved и `ret`'ом «возвращается» туда, где новый поток остановился.
//!
//! # Старт нового потока через трамплин
//!
//! Стек свежего потока [`init_thread_stack`] готовит так, что первый `ret` прыгает не
//! сразу в точку входа, а в трамплин `ferros_thread_trampoline`. Трамплин:
//! 1. делает `sti` — поток должен работать с **включёнными** прерываниями (иначе его
//!    не сможет вытеснить таймер в M4e, и пока поток работает, IRQ'и терялись бы);
//! 2. делает `call` реальной точки входа (её адрес лежит в `r15`). Именно `call`, а не
//!    `jmp`, чтобы на входе в `entry` стек был выровнен по ABI (`rsp ≡ 8 mod 16`).
//!
//! # Почему ту же [`switch_context`] можно звать из обработчика прерывания (M4e)
//!
//! При вытеснении [`switch_context`] вызывается прямо из обработчика таймера, а не из
//! обычного кода. Это корректно, и вот почему весь контекст потока оказывается сохранён:
//!
//! - **caller-saved** (`rax`, `rcx`, `rdx`, `rsi`, `rdi`, `r8`–`r11`) — обработчик
//!   объявлен `extern "x86-interrupt"` и содержит вызовы (EOI, сам `switch_context`).
//!   Любой `call` по System V затирает caller-saved, поэтому компилятор обязан сохранить
//!   их все в прологе обработчика и вернуть в эпилоге перед `iretq`.
//! - **callee-saved** (`rbx`, `rbp`, `r12`–`r15`) — их кладёт на стек сама
//!   [`switch_context`] и снимает при возврате в этот поток.
//! - **`rsp`** — переключает [`switch_context`]; **`rip`/`rflags`** — в кадре прерывания,
//!   их вернёт `iretq` обработчика.
//!
//! Когда поток снова получит CPU, [`switch_context`] вернётся внутрь его обработчика
//! таймера, тот доработает и `iretq`'ом восстановит прерванное место. Прерванный поток
//! не замечает, что его подменяли — поэтому вытеснение работает на той же asm, что и
//! кооперативный `yield`.

use super::gdt;
use x86_64::registers::control::Cr3;
use x86_64::registers::model_specific::FsBase;
use x86_64::structures::paging::PhysFrame;
use x86_64::VirtAddr;

// Ассемблер: чистый пролог/эпилог без участия компилятора. Синтаксис Intel (по
// умолчанию в Rust). Аргументы switch_context по System V: rdi = old_rsp (куда
// сохранить текущий rsp), rsi = new_rsp (какой rsp восстановить).
core::arch::global_asm!(
    ".global ferros_switch_context",
    "ferros_switch_context:",
    "    push rbp",
    "    push rbx",
    "    push r12",
    "    push r13",
    "    push r14",
    "    push r15",
    "    mov [rdi], rsp", // сохранить rsp текущего потока в *old_rsp
    "    mov rsp, rsi",   // переключиться на стек нового потока
    "    pop r15",
    "    pop r14",
    "    pop r13",
    "    pop r12",
    "    pop rbx",
    "    pop rbp",
    "    ret", // «вернуться» в новый поток (его сохранённый адрес возврата)
    // Трамплин старта нового потока: r15 = реальная точка входа.
    ".global ferros_thread_trampoline",
    "ferros_thread_trampoline:",
    "    sti",      // новый поток работает с включёнными прерываниями
    "    call r15", // зовём entry (call выравнивает стек по ABI на входе в неё)
    // entry имеет тип `-> !` и не должна возвращаться; на всякий случай — стоп.
    "2:",
    "    cli",
    "    hlt",
    "    jmp 2b",
);

// Трамплин старта ПОЛЬЗОВАТЕЛЬСКОГО потока (M5c3): после первого переключения сюда
// switch_context уже снял callee-saved, в которых [`init_user_thread_stack`] спрятал
// параметры входа в кольцо 3: r15=точка входа, r14=вершина user-стека, r13=user CS,
// r12=user SS. Трамплин собирает кадр `iretq` и уходит в кольцо 3 с IF=1 (поток
// вытесняемый). CR3 на адресное пространство процесса уже переключён планировщиком.
core::arch::global_asm!(
    ".global ferros_user_thread_trampoline",
    "ferros_user_thread_trampoline:",
    "    push r12",   // SS = user_ss
    "    push r14",   // RSP = вершина user-стека
    "    push 0x202", // RFLAGS: IF=1 (бит 9) + зарезерв. бит 1 → вытесняемый кольцо-3 поток
    "    push r13",   // CS = user_cs
    "    push r15",   // RIP = точка входа
    "    iretq",
);

extern "C" {
    fn ferros_switch_context(old_rsp: *mut u64, new_rsp: u64);
    fn ferros_thread_trampoline();
    fn ferros_user_thread_trampoline();
}

/// Переключает контекст с текущего потока на другой.
///
/// Сохраняет callee-saved и `rsp` текущего потока (записывая `rsp` в `*old_rsp`),
/// затем восстанавливает контекст потока с `new_rsp`. Возврат из этой функции
/// произойдёт, когда кто-нибудь переключится обратно на текущий поток.
///
/// # Safety
///
/// `old_rsp` должен указывать на валидную ячейку для сохранения `rsp`. `new_rsp`
/// должен быть корректным сохранённым (или подготовленным [`init_thread_stack`])
/// указателем стека. Вызывать с выключенными прерываниями.
pub unsafe fn switch_context(old_rsp: *mut u64, new_rsp: u64) {
    ferros_switch_context(old_rsp, new_rsp);
}

/// Готовит стек нового потока так, чтобы первое переключение на него ушло в трамплин,
/// а тот включил прерывания и вызвал `entry`. Возвращает начальный `rsp` потока.
///
/// Раскладка кадра (от старших адресов к младшим):
/// `[trampoline][rbp=0][rbx=0][r12=0][r13=0][r14=0][r15=entry]`. При переключении
/// [`switch_context`] снимет шесть callee-saved (в т.ч. `r15 = entry`), а `ret`
/// заберёт адрес трамплина.
///
/// # Safety
///
/// `stack_top` должен указывать на вершину (старший адрес) выделенной, выровненной по
/// 16 байт области стека, в которой есть место хотя бы под 7 машинных слов. `entry`
/// не должна возвращаться (тип `-> !`): возвращаться ей некуда.
pub unsafe fn init_thread_stack(stack_top: *mut u8, entry: extern "C" fn() -> !) -> u64 {
    let mut sp = stack_top as *mut u64;

    // Адрес возврата: первый `ret` прыгнет в трамплин.
    sp = sp.sub(1);
    sp.write(ferros_thread_trampoline as *const () as usize as u64);

    // Пять нулевых callee-saved: rbp, rbx, r12, r13, r14.
    for _ in 0..5 {
        sp = sp.sub(1);
        sp.write(0);
    }

    // r15 = реальная точка входа: трамплин её вызовет.
    sp = sp.sub(1);
    sp.write(entry as usize as u64);

    sp as u64
}

/// Готовит **ядровый** стек нового пользовательского потока так, чтобы первое
/// переключение на него ушло в [`ferros_user_thread_trampoline`], а тот `iretq`'нул в
/// кольцо 3 на `entry` с пользовательским стеком `user_stack_top` (M5c3). Возвращает
/// начальный `rsp` (в ядровом стеке) для сохранения в контексте потока.
///
/// Раскладка кадра (от старших адресов к младшим), под `pop`-последовательность
/// `switch_context` (`r15,r14,r13,r12,rbx,rbp`, затем `ret`):
/// `[user_trampoline][rbp=0][rbx=0][r12=user_ss][r13=user_cs][r14=user_stack][r15=entry]`.
///
/// # Safety
///
/// `kstack_top` — вершина выделенного, выровненного по 16 байт ЯДРОВОГО стека (минимум 7
/// машинных слов). `entry`/`user_stack_top` должны указывать в отображённую и доступную из
/// кольца 3 память адресного пространства этого процесса; `user_cs`/`user_ss` — валидные
/// селекторы кольца 3 (RPL=3). CR3 на адресное пространство процесса переключает
/// планировщик перед первым входом.
pub unsafe fn init_user_thread_stack(
    kstack_top: *mut u8,
    entry: u64,
    user_stack_top: u64,
    user_cs: u64,
    user_ss: u64,
) -> u64 {
    let mut sp = kstack_top as *mut u64;
    let mut push = |value: u64| {
        // SAFETY: sp идёт вниз по выделенному ядровому стеку достаточного размера.
        unsafe {
            sp = sp.sub(1);
            sp.write(value);
        }
    };

    push(ferros_user_thread_trampoline as *const () as u64); // адрес возврата (ret → трамплин)
    push(0); // rbp
    push(0); // rbx
    push(user_ss); // r12
    push(user_cs); // r13
    push(user_stack_top); // r14
    push(entry); // r15

    sp as u64
}

/// Корень таблиц страниц (PML4) текущего адресного пространства — из `CR3`. Планировщик
/// запоминает им адресное пространство ядра, чтобы возвращаться в него.
pub fn current_address_space() -> PhysFrame {
    Cr3::read().0
}

/// Переключение задачи планировщиком (M5c3): ставит стек ядра следующей задачи (rsp0 в
/// TSS), при необходимости переключает адресное пространство (`CR3`) и затем переключает
/// контекст ([`switch_context`]). Объединено в один арх-шов, чтобы переносимый `sched` не
/// трогал `CR3`/TSS напрямую.
///
/// Память ядра отображена в КАЖДОМ адресном пространстве (общие L4-записи), поэтому всё,
/// чего касается `switch_context` (стеки/таблицы ядра), доступно и после смены `CR3`.
///
/// `next_fs_base` — база сегмента FS следующей задачи (её TLS-указатель, M9b): восстанавливаем её
/// на каждом переключении, иначе TLS одного процесса протёк бы в другой (база FS — глобальный
/// регистр CPU, MSR `IA32_FS_BASE`). У потоков ядра и не настроивших TLS процессов она 0.
///
/// # Safety
/// Вызывать с **выключенными прерываниями** (как [`switch_context`]). `old_rsp`/`new_rsp` —
/// валидные контексты потоков; `next_cr3` — корректный PML4, в котором отображено ядро;
/// `next_rsp0` — вершина стека ядра следующей задачи; `next_fs_base` — каноничный адрес
/// (валидатор в `arch_prctl` это гарантирует).
pub unsafe fn switch_task(
    old_rsp: *mut u64,
    new_rsp: u64,
    next_cr3: PhysFrame,
    next_rsp0: u64,
    next_fs_base: u64,
) {
    // SAFETY: rsp0 пишем с IF=0 (требование set_kernel_stack).
    unsafe { gdt::set_kernel_stack(VirtAddr::new(next_rsp0)) };

    // База FS следующей задачи (TLS). Пишем безусловно (в т.ч. 0 для потоков ядра): чужое
    // значение в MSR не должно «прилипнуть» к следующей задаче. Адрес каноничен (его проверил
    // `arch_prctl` перед сохранением), поэтому `VirtAddr::new` не паникует.
    FsBase::write(VirtAddr::new(next_fs_base));

    // Тот же стек — под `syscall` этого процесса (M6f4): блокирующий вызов (`wait`) уступает
    // CPU из середины обработки syscall, не затирая чужой кадр на общем стеке. Только для задач
    // со своим ядровым стеком (rsp0 != 0); у «нулевого» потока ядра его нет, но он и не делает
    // syscall'ов, поэтому прежнее значение оставляем.
    if next_rsp0 != 0 {
        super::syscall::set_syscall_stack(next_rsp0);
    }

    let (active, flags) = Cr3::read();
    if next_cr3 != active {
        // SAFETY: next_cr3 — валидный PML4 с отображённым ядром; переключаемся на него.
        unsafe { Cr3::write(next_cr3, flags) };
    }

    // SAFETY: см. контракт функции; контексты валидны, прерывания выключены.
    unsafe { switch_context(old_rsp, new_rsp) };
}
