//! Архитектура x86_64: код, завязанный на конкретный CPU и платформу PC.
//!
//! Здесь живут таблицы дескрипторов (GDT/TSS) и обработка прерываний (IDT/PIC) —
//! всё, что нельзя перенести на ARM/RISC-V без переписывания. Переносимое ядро
//! обращается сюда только через [`init`] и публичные элементы подмодулей.

pub mod context;
pub mod gdt;
pub mod interrupts;
pub mod io;
pub mod pci;
pub mod syscall;

/// Верхняя граница пользовательской половины адресного пространства: на x86-64 с
/// 4-уровневыми таблицами канонические пользовательские адреса — это `[0, 2^47)`, выше —
/// «дыра» неканонических адресов и половина ядра. Переносимый код проверяет указатели
/// пользователя через арх-нейтральный псевдоним [`crate::arch::USER_SPACE_END`].
pub const USER_SPACE_END: u64 = 0x0000_8000_0000_0000;

/// Начало кучи процесса (M9a, `brk`). Лежит в том же приватном L4-слоте 255, что ELF
/// (`0x7F80_0000_0000`) и страница стека (`USER_STACK_VA` = `0x7F80_1000_0000`), но на 256 МиБ
/// выше стека — куча растёт ВВЕРХ от этой базы, в сторону [`USER_HEAP_MAX`], и за все разумные
/// размеры не дотягивается ни до стека снизу, ни до чужих маппингов. Должна быть выровнена по
/// странице (4 КиБ): инвариант `brk` — «отображены ровно страницы `[USER_HEAP_BASE, ⌈brk⌉)`».
pub const USER_HEAP_BASE: u64 = 0x7F80_2000_0000;

/// Верхний предел кучи (M9a): `brk` выше этого адреса отклоняется (возвращает текущий разрыв,
/// как Linux при нехватке памяти). 1 ГиБ от базы — с запасом для libc/реальных программ, но
/// ограничено, чтобы битый `brk` не пытался отобразить пол-адресного-пространства.
pub const USER_HEAP_MAX: u64 = USER_HEAP_BASE + 0x4000_0000;

// Куча обязана начинаться на границе страницы (инвариант отображения `brk`) и лежать ниже
// верхней границы пользовательской половины.
const _: () = assert!(USER_HEAP_BASE.is_multiple_of(4096));
const _: () = assert!(USER_HEAP_MAX > USER_HEAP_BASE && USER_HEAP_MAX < USER_SPACE_END);

/// Инициализация процессора под x86_64.
///
/// Порядок критичен: сначала GDT+TSS (даёт IST-стек для double fault и селекторы колец),
/// затем IDT (ссылается на IST-стек), затем настройка `syscall` (берёт селекторы из GDT),
/// затем перемап PIC и `sti`. После `sti` ядро реагирует на аппаратные прерывания.
pub fn init() {
    gdt::init();
    interrupts::init_idt();
    // M5: настройка инструкции `syscall` (MSR STAR/LSTAR/SFMASK, EFER.SCE). После GDT —
    // нужны её селекторы колец 0/3.
    syscall::init();
    // SAFETY: PIC перемаплен на свободные векторы 32..47 (см. interrupts.rs);
    // исключения CPU (0..31) не затронуты.
    unsafe { interrupts::PICS.lock().initialize() };
    // `sti` — разрешаем аппаратные прерывания.
    x86_64::instructions::interrupts::enable();
}
